class OpenEvolveStandardAdapter(OpenEvolveFallbackAdapter):
    """
    Standard evolutionary algorithm adapter

    Uses traditional evolutionary algorithms without specialized modes
    """

    async def evolve(
        self,
        problem: str,
        domain: str = "general",
        **kwargs
    ) -> Dict[str, Any]:
        """Execute standard evolution"""
        logger.info("Using standard evolutionary algorithm")

        # Override mode to standard
        self.config['evolution_mode'] = 'standard'

        return await super().evolve(problem, domain, **kwargs)


