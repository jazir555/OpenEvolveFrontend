def create_openevolve_adapter(config: Dict[str, Any]) -> OpenEvolveFallbackAdapter:
    """
    Factory function to create appropriate OpenEvolve adapter

    Args:
        config: Configuration dictionary

    Returns:
        Appropriate adapter instance based on config
    """
    mode = config.get('evolution_mode', 'standard')

    # Map modes to adapters
    adapter_map = {
        'standard': OpenEvolveStandardAdapter,
        'qd': OpenEvolveQDAdapter,
        'mo': OpenEvolveMOAdapter,
        'adversarial': OpenEvolveAdversarialAdapter
    }

    adapter_class = adapter_map.get(mode, OpenEvolveStandardAdapter)

    logger.info(f"Creating OpenEvolve adapter for mode: {mode}")
    return adapter_class(config)
