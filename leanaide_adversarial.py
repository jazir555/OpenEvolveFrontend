class ProofApproach(Enum):
    """Different approaches to generating proofs"""
    CONSTRUCTIVE = "constructive"  # Build proof explicitly
    CLASSICAL = "classical"  # Use classical reasoning
    COMPUTATIONAL = "computational"  # Use computation/decidability
    INDIRECT = "indirect"  # Proof by contradiction
    STRUCTURAL = "structural"  # Exploit structure of objects
    ALGEBRAIC = "algebraic"  # Use algebraic manipulations


class CritiqueSeverity(Enum):
    """Severity levels for proof critiques"""
    CRITICAL = "critical"  # Proof is invalid
    HIGH = "high"  # Significant gap or flaw
    MEDIUM = "medium"  # Minor issue or weakness
    LOW = "low"  # Style or clarity issue"
    INFO = "info"  # Suggestion for improvement"


class CounterexampleStatus(Enum):
    """Status of counterexample validation"""
    VALID = "valid"  # Counterexample disproves theorem
    INVALID = "invalid"  # Counterexample doesn't work
    INCONCLUSIVE = "inconclusive"  # Cannot verify
    PENDING = "pending"  # Awaiting verification


