class LeanAdversarialEvolutionMDAP:
    """
    Adversarial evolution with MDAP agent voting.

    Blue Team and Red Team use MDAP voting for:
    - Blue Team: Multi-agent proof strategy generation
    - Red Team: Multi-agent proof critique
    - Enhanced adversarial rounds with consensus
    """

    def __init__(
        self,
        blue_agents: List[LeanBlueTeamAgent],
        red_agents: List[LeanRedTeamAgent],
        mdap_config: Optional['LeanMDAPConfig'] = None
    ):
        """
        Initialize MDAP-enhanced adversarial evolution.

        Args:
            blue_agents: List of blue team agents
            red_agents: List of red team agents
            mdap_config: MDAP configuration
        """
        self.blue_agents = blue_agents
        self.red_agents = red_agents
        self.mdap_config = mdap_config

        # Statistics tracking
        self.mdap_stats = {
            "blue_team_votes": defaultdict(int),
            "red_team_votes": defaultdict(int),
            "consensus_rates": [],
            "agent_contributions": defaultdict(int)
        }

    async def blue_team_generate_with_mdap(
        self,
        theorem: str,
        agents: List[LeanBlueTeamAgent],
        context: Optional[ProofContext] = None
    ) -> LeanProofStrategy:
        """
        Generate proof strategy using MDAP voting among blue team agents.

        Args:
            theorem: Theorem to prove
            agents: List of blue team agents
            context: Proof context

        Returns:
            Consensus proof strategy
        """
        if context is None:
            context = ProofContext()

        logger.info(f"Blue team MDAP generation with {len(agents)} agents")

        # Each agent generates a strategy
        strategies = []
        for agent in agents:
            strategy = agent.generate_proof_strategy(
                theorem, context, approach=None
            )
            strategies.append(strategy)

        # MDAP voting on best strategy
        consensus_strategy = await self._mdap_vote_on_strategy(strategies)

        # Track voting statistics
        for strategy in strategies:
            self.mdap_stats["blue_team_votes"][strategy.approach] += 1

        logger.info(f"MDAP selected {consensus_strategy.approach} strategy")
        return consensus_strategy

    async def red_team_critique_with_mdap(
        self,
        proof: LeanProof,
        agents: List[LeanRedTeamAgent],
        theorem: str,
        context: Optional[ProofContext] = None
    ) -> List[ProofCritique]:
        """
        Critique proof using MDAP voting among red team agents.

        Args:
            proof: Proof to critique
            agents: List of red team agents
            theorem: Theorem being proved
            context: Proof context

        Returns:
            Consensus list of critiques
        """
        if context is None:
            context = ProofContext()

        logger.info(f"Red team MDAP critique with {len(agents)} agents")

        # Each agent critiques the proof
        all_critiques = []
        for agent in agents:
            agent_critiques = agent.critique_proof(proof, theorem, context)
            all_critiques.extend(agent_critiques)

        # MDAP voting on most important critiques
        consensus_critiques = await self._mdap_vote_on_critiques(all_critiques)

        # Track voting statistics
        for critique in consensus_critiques:
            self.mdap_stats["red_team_votes"][critique.severity] += 1

        logger.info(f"MDAP selected {len(consensus_critiques)} consensus critiques")
        return consensus_critiques

    async def run_adversarial_round_with_mdap(
        self,
        blue_agents: List[LeanBlueTeamAgent],
        red_agents: List[LeanRedTeamAgent],
        theorem: str,
        context: Optional[ProofContext] = None,
        round_number: int = 1
    ) -> RoundResult:
        """
        Run a single adversarial round with MDAP voting.

        Args:
            blue_agents: Blue team agents
            red_agents: Red team agents
            theorem: Theorem to prove
            context: Proof context
            round_number: Current round number

        Returns:
            RoundResult with MDAP-enhanced adversarial round
        """
        start_time = time.time()

        if context is None:
            context = ProofContext()

        # Blue Team: Generate proof with MDAP
        logger.info(f"Round {round_number}: Blue Team MDAP generation...")
        blue_strategy = await self.blue_team_generate_with_mdap(
            theorem, blue_agents, context
        )

        # Red Team: Critique with MDAP
        logger.info(f"Round {round_number}: Red Team MDAP critique...")
        red_critique = await self.red_team_critique_with_mdap(
            blue_strategy, red_agents, theorem, context
        )

        # Score the round
        blue_survived = len([c for c in red_critique
                           if c.severity in [CritiqueSeverity.CRITICAL, CritiqueSeverity.HIGH]]) == 0

        red_score = min(1.0, len(red_critique) / 10.0)
        blue_score = blue_strategy.confidence if blue_survived else max(0.0, blue_strategy.confidence - 0.3)

        # Track consensus rate
        consensus_rate = self._calculate_consensus_rate(blue_strategy, red_critique)
        self.mdap_stats["consensus_rates"].append(consensus_rate)

        round_result = RoundResult(
            round_number=round_number,
            blue_strategy=blue_strategy,
            red_critique=red_critique,
            counterexamples=[],
            blue_survived=blue_survived,
            red_score=red_score,
            blue_score=blue_score,
            time_taken=time.time() - start_time,
            metadata={"mdap_enhanced": True, "consensus_rate": consensus_rate}
        )

        logger.info(
            f"Round {round_number}: Blue={blue_score:.2f}, Red={red_score:.2f}, "
            f"Survived={blue_survived}, Consensus={consensus_rate:.2f}"
        )

        return round_result

    async def _mdap_vote_on_strategy(
        self,
        strategies: List[LeanProofStrategy]
    ) -> LeanProofStrategy:
        """
        Use MDAP voting to select best strategy.

        Args:
            strategies: List of strategies to vote on

        Returns:
            Consensus strategy
        """
        if not strategies:
            raise ValueError("No strategies to vote on")

        if len(strategies) == 1:
            return strategies[0]

        # Score each strategy
        scored_strategies = []
        for strategy in strategies:
            # Combined score from confidence, complexity, and elegance
            score = (
                strategy.confidence * 0.5 +
                (1.0 - strategy.estimated_complexity) * 0.3 +
                strategy.performance_history.get("avg_success", 0.5) * 0.2
            )
            scored_strategies.append((strategy, score))

        # Sort by score
        scored_strategies.sort(key=lambda x: x[1], reverse=True)

        # First-K-ahead voting: select top strategy
        k_ahead = self.mdap_config.k_ahead_threshold if self.mdap_config else 3
        top_k = min(k_ahead, len(scored_strategies))

        # In full MDAP, agents would vote here
        # For now, return highest scored
        return scored_strategies[0][0]

    async def _mdap_vote_on_critiques(
        self,
        critiques: List[ProofCritique]
    ) -> List[ProofCritique]:
        """
        Use MDAP voting to select most important critiques.

        Args:
            critiques: List of critiques to vote on

        Returns:
            Consensus critiques
        """
        if not critiques:
            return []

        # Group by issue type
        by_type = defaultdict(list)
        for critique in critiques:
            by_type[critique.issue_type].append(critique)

        # Select best critique for each type
        consensus = []
        for issue_type, type_critiques in by_type.items():
            # Sort by severity and confidence
            sorted_critiques = sorted(
                type_critiques,
                key=lambda c: (c.severity.value, c.confidence),
                reverse=True
            )
            consensus.append(sorted_critiques[0])

        # Sort by overall importance
        consensus.sort(
            key=lambda c: (c.severity.value, c.confidence),
            reverse=True
        )

        return consensus

    def _calculate_consensus_rate(
        self,
        strategy: LeanProofStrategy,
        critiques: List[ProofCritique]
    ) -> float:
        """Calculate rate of consensus among agents."""
        # Simplified consensus calculation
        if not critiques:
            return 1.0

        # Consensus is higher when critiques are less severe
        severity_weights = {
            CritiqueSeverity.CRITICAL: 0.0,
            CritiqueSeverity.HIGH: 0.3,
            CritiqueSeverity.MEDIUM: 0.6,
            CritiqueSeverity.LOW: 0.8,
            CritiqueSeverity.INFO: 1.0
        }

        weights = [severity_weights.get(c.severity, 0.5) for c in critiques]
        return sum(weights) / len(weights) if weights else 0.0

    def get_mdap_statistics(self) -> Dict[str, Any]:
        """Get MDAP voting statistics."""
        avg_consensus = 0.0
        if self.mdap_stats["consensus_rates"]:
            avg_consensus = sum(self.mdap_stats["consensus_rates"]) / len(self.mdap_stats["consensus_rates"])

        return {
            "blue_team_votes": dict(self.mdap_stats["blue_team_votes"]),
            "red_team_votes": dict(self.mdap_stats["red_team_votes"]),
            "average_consensus_rate": avg_consensus,
            "agent_contributions": dict(self.mdap_stats["agent_contributions"])
        }


